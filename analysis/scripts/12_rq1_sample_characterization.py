#!/usr/bin/env python3
"""
Step 12 (v1.0): the RQ1 sample-characterization numbers at the population level:
  - distinct repositories and distinct task creators,
  - the entry-point distribution (4 buckets),
  - the entry-point by ask-type cross-tabulation (% within each entry bucket),
  - the review-request share of Validation asks.

All of it comes from the labelled population (sample/rq1_task_labels.csv) and local
parquet only. It writes outputs/rq1_sample_char.txt and
outputs/tables/rq1_samplechar_macros.tex.
"""
from pathlib import Path
import json, duckdb, pandas as pd
PROJECT=Path(__file__).resolve().parent.parent
DATA=PROJECT/"data"/"dataset_v1.0"
OUT=PROJECT/"outputs"; (OUT/"tables").mkdir(parents=True,exist_ok=True)
SESS=f"read_parquet('{DATA}/agent_sessions/*.parquet')"
TASKS=f"read_parquet('{DATA}/agent_tasks/*.parquet')"
LAB=f"read_csv_auto('{PROJECT/'sample'/'rq1_task_labels.csv'}')"
emap={e["raw"]:e["bucket"] for e in json.loads((PROJECT/"_working"/"entrypoint_mapping_draft.json").read_text())}
REVIEW_RAW={"review-request","pull_request_review","pull_request_review_non_copilot_pull_request"}
con=duckdb.connect()
# per-task: ask_type (label) + repo + creator + first-session event.type
df=con.sql(f"""
  WITH firsts AS (SELECT s.task.id tid, any_value(s.event.type) et
                  FROM {SESS} s WHERE s.session_index=0 GROUP BY s.task.id)
  SELECT l.task_id tid, l.ask_type atype,
         t.repository.full_name repo, t.creator.login creator,
         f.et et
  FROM {LAB} l
  JOIN {TASKS} t ON t.id=l.task_id
  LEFT JOIN firsts f ON f.tid=l.task_id
""").df()
df["bucket"]=df.et.map(emap).fillna("other")
df["is_review"]=df.et.isin(REVIEW_RAW)
N=len(df)
S=[]; w=lambda x="": (S.append(str(x)), print(x))
w(f"labelled population tasks: {N:,}")
w(f"distinct repositories: {df.repo.nunique():,}")
w(f"distinct task creators: {df.creator.nunique():,}")
w("\nentry-point distribution:")
bd=df.bucket.value_counts(normalize=True).mul(100).round(1)
for b in ["pr_comment","issue_assignment","web_interface","external_tool","other"]:
    if b in bd: w(f"  {b:16s} {bd[b]:5.1f}%  (n={int((df.bucket==b).sum()):,})")
w("\nentry-point x ask-type (% within each entry bucket):")
ct=pd.crosstab(df.bucket,df.atype,normalize="index").mul(100).round(1)
w(ct.to_string())
w("\nreview-request share of Validation asks:")
va=df[df.atype=="Validation"]
w(f"  Validation tasks: {len(va):,}; via review-request event: {va.is_review.mean()*100:.1f}%")
(OUT/"rq1_sample_char.txt").write_text("\n".join(S)+"\n")

# macros
def pc(b): return f"{bd.get(b,0):.1f}"
def cell(b,a): return f"{ct.loc[b,a]:.1f}" if (b in ct.index and a in ct.columns) else "0.0"
mac=["% Generated by scripts/12_rq1_sample_characterization.py -- do not edit by hand.",
 f"\\newcommand{{\\rqNRepos}}{{{df.repo.nunique():,}}}".replace(",","{,}"),
 f"\\newcommand{{\\rqNCreators}}{{{df.creator.nunique():,}}}".replace(",","{,}"),
 f"\\newcommand{{\\rqEntryPR}}{{{pc('pr_comment')}}}",
 f"\\newcommand{{\\rqEntryIssue}}{{{pc('issue_assignment')}}}",
 f"\\newcommand{{\\rqEntryWeb}}{{{pc('web_interface')}}}",
 f"\\newcommand{{\\rqEntryExt}}{{{pc('external_tool')}}}",
 f"\\newcommand{{\\rqIssueCA}}{{{cell('issue_assignment','Code Authoring')}}}",
 f"\\newcommand{{\\rqIssueFR}}{{{cell('issue_assignment','Failure Reporting')}}}",
 f"\\newcommand{{\\rqPRcommCA}}{{{cell('pr_comment','Code Authoring')}}}",
 f"\\newcommand{{\\rqPRcommVA}}{{{cell('pr_comment','Validation')}}}",
 f"\\newcommand{{\\rqReviewShareVA}}{{{va.is_review.mean()*100:.0f}}}",
]
(OUT/"tables"/"rq1_samplechar_macros.tex").write_text("\n".join(mac)+"\n")
w("\nwrote outputs/rq1_sample_char.txt and tables/rq1_samplechar_macros.tex")
