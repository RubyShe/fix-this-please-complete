#!/usr/bin/env python3
"""
Step 04 (v1.0): RQ2 Table IV and the statistics, grouped by RQ1 ask type.

Unit: every task whose first session carries a label (the RQ1 primary main category,
from scripts/07). The per-task metrics come from scripts/02.

The paper's cost metric is output tokens (scripts/11_tokens_primary.py). This script
produces the merge-rate and change-size columns of Table II and the per-type merge and
change statistics. It also computes credit, cost-per-merged, and wasted-credit columns,
but those are legacy: credits are only a secondary figure now, and the paper does not use
them.

Per ask type we report (medians unless noted):
  Rounds:          median human_iterations (sessions beyond the first)
  Credits:         median cost (premium-request credits, floor estimate) [legacy/secondary]
  Merge rate:      merged / (merged + closed), over resolved PRs
  Change size:     median added-plus-deleted lines (with IQR)
  Cost per merged: summed credits of resolved tasks / the number merged (open excluded)
  Wasted credits:  credits on non-merged tasks (closed or no PR) / the total (open excluded)
  Tokens (in/out): left as a TODO here; the per-session token counts live only in the
                   63 GB agent_session_logs, which we did not download in this step.

Tests: Kruskal-Wallis across types on rounds, credits, and change size, then pairwise
Mann-Whitney with Holm correction and Cliff's delta; chi-square on merge rate, with
pairwise two-proportion tests (Holm). With a population this large almost everything is
significant, so we read the effect sizes rather than the p-values.

Outputs:
  outputs/rq2_table_iv.csv: per-type metrics
  (the RQ2 outcomes table is generated by scripts/11 as rq2_table_outcomes.tex)
  outputs/tables/rq2_macros.tex: one LaTeX macro per headline number, for the prose
  outputs/rq2_stats.txt: the test results
"""
from __future__ import annotations
import argparse, itertools
from pathlib import Path
import numpy as np, pandas as pd
from scipy import stats

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent
OUT = PROJECT / "outputs"; (OUT / "tables").mkdir(parents=True, exist_ok=True)
METRICS = OUT / "rq2_task_metrics_v1.0.parquet"

ap = argparse.ArgumentParser()
ap.add_argument("--labels", default=str(PROJECT / "sample" / "rq1_task_labels.csv"))
ap.add_argument("--cost", default="cost_credits", help="cost column (floor estimate by default)")
a = ap.parse_args()

CATS = ["Code Authoring","Failure Reporting","Inquiry","Validation","Delegation","Others"]
SHORT = {"Code Authoring":"CA","Failure Reporting":"FR","Inquiry":"IN",
         "Validation":"VA","Delegation":"DE","Others":"OT"}
COST = a.cost

def read_metrics(p):
    try: return pd.read_parquet(p)
    except Exception:
        import duckdb; return duckdb.sql(f"SELECT * FROM read_parquet('{p}')").df()

m = read_metrics(METRICS)
lab = pd.read_csv(a.labels)
df = m.merge(lab[["task_id","ask_type"]], on="task_id", how="inner")
print(f"[info] {len(df):,} labelled tasks joined.")

def med(s): return float(np.median(s)) if len(s) else float("nan")
def iqr(s):
    s = np.asarray(s, float)
    return (np.percentile(s,25), np.percentile(s,75)) if len(s) else (np.nan,np.nan)

def cliffs(a_, b_):
    a_, b_ = np.asarray(a_,float), np.asarray(b_,float)
    if len(a_)==0 or len(b_)==0: return float("nan")
    U = stats.mannwhitneyu(a_, b_, alternative="two-sided").statistic
    return 2.0*U/(len(a_)*len(b_)) - 1.0

def holm(ps):
    ps = np.asarray(ps,float); mN=len(ps); order=np.argsort(ps); adj=np.empty(mN); run=0.0
    for i,idx in enumerate(order):
        run=max(run,(mN-i)*ps[idx]); adj[idx]=min(run,1.0)
    return adj

# ---------- per-type metrics ----------
rows=[]
def metrics_for(g):
    resolved = g[g.merge_status.isin(["merged","closed_no_merge"])]
    merged = (g.merge_status=="merged").sum()
    mr = 100.0*merged/len(resolved) if len(resolved) else float("nan")
    # cost per merged change: credits of resolved tasks / # merged
    cpm = resolved[COST].sum()/merged if merged else float("nan")
    # wasted: credits on non-merged (closed or no_pr) / credits excluding open
    nonopen = g[g.merge_status!="open"]
    nonmerged = g[g.merge_status.isin(["closed_no_merge","no_pr"])]
    wasted = 100.0*nonmerged[COST].sum()/nonopen[COST].sum() if nonopen[COST].sum()>0 else float("nan")
    lo,hi = iqr(g.lines_changed.dropna())
    return dict(n=len(g), rounds=med(g.developer_rounds), credits=med(g[COST]),
                merge_rate=mr, change=med(g.lines_changed.dropna()), change_lo=lo, change_hi=hi,
                cost_per_merged=cpm, wasted=wasted, merged=int(merged), resolved=int(len(resolved)))
for cat in CATS:
    g=df[df.ask_type==cat]
    if len(g): rows.append({"ask_type":cat, **metrics_for(g)})
allrow={"ask_type":"All", **metrics_for(df)}
tbl=pd.DataFrame(rows+[allrow])
tbl.to_csv(OUT/"rq2_table_iv.csv", index=False)
print("\n=== Table IV ==="); print(tbl.to_string(index=False))

# ---------- stats ----------
S=[]
def w(x=""): S.append(x)
tested=[c for c in CATS if len(df[df.ask_type==c])>=10]
for col,lbl in [("developer_rounds","rounds"),(COST,"credits"),("lines_changed","change size")]:
    w(f"\n=== {lbl}: Kruskal-Wallis across ask types ===")
    groups=[df[df.ask_type==c][col].dropna().values for c in tested]
    H,p=stats.kruskal(*groups); w(f"H={H:.1f}, p={p:.3g}")
    raw=[]
    for x,y in itertools.combinations(tested,2):
        a_=df[df.ask_type==x][col].dropna().values; b_=df[df.ask_type==y][col].dropna().values
        _,pv=stats.mannwhitneyu(a_,b_,alternative="two-sided"); raw.append((x,y,pv,cliffs(a_,b_)))
    adj=holm([r[2] for r in raw])
    w("  pair | Holm p | Cliff's delta (|d|>=0.147 small, 0.33 medium, 0.474 large)")
    for (x,y,pv,d),pa in sorted(zip(raw,adj), key=lambda r:-abs(r[0][3])):
        w(f"    {x} vs {y}: p={pa:.2g}, d={d:+.2f}")
w("\n=== merge rate: chi-square across ask types (resolved PRs) ===")
cont=[]
for c in tested:
    r=df[(df.ask_type==c)&(df.merge_status.isin(["merged","closed_no_merge"]))]
    cont.append([(r.merge_status=="merged").sum(),(r.merge_status=="closed_no_merge").sum()])
cont=np.array(cont); chi2,p,dof,_=stats.chi2_contingency(cont)
w(f"chi2={chi2:.1f}, dof={dof}, p={p:.3g}")
(OUT/"rq2_stats.txt").write_text("\n".join(S)+"\n")
print("\n".join(S))

# ---------- LaTeX macros ----------
def f1(x): return f"{x:.1f}"
def f0(x): return f"{x:.0f}"
byc={r["ask_type"]:r for r in rows}
mac=["% Generated by scripts/04_rq2_tableIV_stats.py -- do not edit by hand."]
for cat in CATS:
    r=byc[cat]; s=SHORT[cat]
    mac.append(f"\\newcommand{{\\rqMerge{s}}}{{{f0(r['merge_rate'])}}}")
    mac.append(f"\\newcommand{{\\rqRounds{s}}}{{{f0(r['rounds'])}}}")
    mac.append(f"\\newcommand{{\\rqCredits{s}}}{{{f0(r['credits'])}}}")
    mac.append(f"\\newcommand{{\\rqChange{s}}}{{{f0(r['change'])}}}")
    mac.append(f"\\newcommand{{\\rqCPM{s}}}{{{f1(r['cost_per_merged'])}}}")
    mac.append(f"\\newcommand{{\\rqWasted{s}}}{{{f0(r['wasted'])}}}")
mac.append(f"\\newcommand{{\\rqMergeAll}}{{{f0(allrow['merge_rate'])}}}")
# derived: highest / lowest merge, cheapest / dearest cost-per-merged, factor
hi=max(rows,key=lambda r:r['merge_rate']); lo=min(rows,key=lambda r:r['merge_rate'])
cpm_vals=[(r['ask_type'],r['cost_per_merged']) for r in rows if r['cost_per_merged']==r['cost_per_merged'] and r['cost_per_merged']>0]
cheap=min(cpm_vals,key=lambda t:t[1]); dear=max(cpm_vals,key=lambda t:t[1])
mac.append(f"\\newcommand{{\\rqMergeHiType}}{{{hi['ask_type']}}}")
mac.append(f"\\newcommand{{\\rqMergeLoType}}{{{lo['ask_type']}}}")
mac.append(f"\\newcommand{{\\rqCPMfactor}}{{{dear[1]/cheap[1]:.1f}}}")
(OUT/"tables"/"rq2_macros.tex").write_text("\n".join(mac)+"\n")
print("wrote rq2_macros.tex")

